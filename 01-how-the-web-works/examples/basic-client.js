// ==========================================
// EXAMPLE: A Raw Node.js HTTP Client
// ==========================================

// 'http' মডিউল ব্যবহার করে আমরা ব্রাউজারের মতো কাজ করবো।
const http = require('http');

// আমরা কোথায় রিকোয়েস্ট পাঠাবো তার অপশন সেট করছি
const options = {
    hostname: 'localhost',
    port: 3000,
    path: '/',
    method: 'GET' // আমরা ডেটা পেতে চাই, তাই GET মেথড
};

// HTTP রিকোয়েস্ট তৈরি করা
console.log('ক্লায়েন্ট: সার্ভারের কাছে অর্ডার পাঠানো হচ্ছে...');

const req = http.request(options, (response) => {
    console.log(`ক্লায়েন্ট: স্ট্যাটাস কোড পেয়েছি: ${response.statusCode}`);
    
    // সার্ভার থেকে ডেটা ছোট ছোট খণ্ডে (chunks) আসে (পরবর্তীতে আমরা Streams সম্পর্কে শিখবো)
    response.on('data', (chunk) => {
        console.log(`ক্লায়েন্ট: ডেটা পেয়েছি -> ${chunk.toString()}`);
    });
});

// যদি কোনো এরর হয় (যেমন: সার্ভার চালু নেই)
req.on('error', (error) => {
    console.error('ক্লায়েন্ট এরর: সার্ভারের সাথে কানেক্ট করা যাচ্ছে না।', error.message);
});

// রিকোয়েস্ট পাঠানো শেষ করা
req.end();

